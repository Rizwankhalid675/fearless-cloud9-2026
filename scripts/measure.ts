/**
 * measure.ts — produce docs/RESULTS.md.
 *
 *     npm run measure                 # the offline priority-sheet advisor
 *     ANTHROPIC_API_KEY=... npm run measure   # adds the model-backed advisor
 *
 * Two numbers, both measured rather than asserted:
 *
 *   1. Does the engine's legal pool match hand-computed ground truth on every
 *      fixture? The fixtures' expected values are arithmetic written out in
 *      tests/fixtures/series.ts, not something legalPool() produced.
 *
 *   2. How much of what an advisor proposes does the gate refuse? That is the
 *      spreadsheet-chaos number: it is how often a coach working from a static
 *      priority sheet would have called an illegal pick.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { RunMetrics } from "../contracts";
import { FIXTURES, CATALOGUE } from "../tests/fixtures/series";
import { legalPool } from "../src/engine/fearless";
import { gateSuggestions, gateStats } from "../src/advisor/gate";
import { tierAdvisor } from "../src/advisor/tier";
import { llmAdvisor } from "../src/advisor/llm";
import type { Advisor } from "../src/advisor/types";
import { DDRAGON_VERSION } from "../src/data/champions";

const PER_FIXTURE = 5;

interface Row {
  advisor: string;
  poolAware: boolean;
  total: number;
  blocked: number;
  burned: number;
  nonexistent: number;
  failures: string[];
}

async function run(advisor: Advisor): Promise<Row> {
  const row: Row = {
    advisor: advisor.name,
    poolAware: advisor.poolAware,
    total: 0,
    blocked: 0,
    burned: 0,
    nonexistent: 0,
    failures: [],
  };

  for (const f of FIXTURES) {
    try {
      const raw = await advisor.suggest(f.side, f.series, PER_FIXTURE);
      const stats = gateStats(gateSuggestions(raw, f.side, f.series));
      row.total += stats.total;
      row.blocked += stats.blocked;
      row.burned += stats.burned;
      row.nonexistent += stats.nonexistent;
    } catch (e) {
      row.failures.push(`${f.name}: ${e instanceof Error ? e.message : String(e)}`);
    }
  }
  return row;
}

function pct(n: number, of: number): string {
  return of === 0 ? "—" : `${((n / of) * 100).toFixed(0)}%`;
}

const startedAt = new Date().toISOString();

// 1. the engine against ground truth
const groundTruth = FIXTURES.map((f) => ({
  name: f.name,
  note: f.note,
  expected: f.expectedLegal,
  actual: legalPool(f.side, f.series).length,
}));
const engineFailures = groundTruth.filter((g) => g.expected !== g.actual);

// 2. the advisors against the gate
const advisors: Advisor[] = [tierAdvisor];
const key = process.env.ANTHROPIC_API_KEY;
if (key) {
  advisors.push(llmAdvisor({ apiKey: key }));
  advisors.push(llmAdvisor({ apiKey: key, tellItThePool: true }));
}
const rows: Row[] = [];
for (const a of advisors) rows.push(await run(a));

const finishedAt = new Date().toISOString();
const headline = rows[0]!;

const metrics: RunMetrics = {
  runId: `measure-${Date.now().toString(36)}`,
  label: headline.advisor,
  startedAt,
  finishedAt,
  headline: {
    name: "illegal suggestions refused by the gate",
    value: headline.blocked,
    unit: `of ${headline.total}`,
  },
  passed: groundTruth.length - engineFailures.length,
  failed: engineFailures.length,
};

const md = `# Results

Generated by \`npm run measure\` on ${startedAt.slice(0, 10)}. Champion catalogue:
${CATALOGUE} champions at Data Dragon patch ${DDRAGON_VERSION}.

## 1. Does the rules engine get the legal pool right?

Each fixture's expected number is arithmetic, written out in
\`tests/fixtures/series.ts\` and checkable by hand. None of it came from
\`legalPool()\` — a fixture built by the code it tests only proves the code
agrees with itself.

| Series state | How the expected number is reached | Expected | Engine | |
|---|---|---:|---:|:--:|
${groundTruth
  .map((g) => `| ${g.name} | ${g.note} | ${g.expected} | ${g.actual} | ${g.expected === g.actual ? "✓" : "✗"} |`)
  .join("\n")}

**${groundTruth.length - engineFailures.length} of ${groundTruth.length} exact.**${
  engineFailures.length ? ` ${engineFailures.length} MISMATCH — see above.` : ""
}

## 2. How much of what an advisor proposes is illegal?

${PER_FIXTURE} suggestions per fixture, ${FIXTURES.length} fixtures, every one
passed through \`gateSuggestions\` before it could be shown.

| Advisor | Knows the pool | Suggestions | Blocked | Already burned | Not a champion |
|---|:--:|---:|---:|---:|---:|
${rows
  .map(
    (r) =>
      `| ${r.advisor} | ${r.poolAware ? "yes" : "no"} | ${r.total} | **${r.blocked}** (${pct(r.blocked, r.total)}) | ${r.burned} | ${r.nonexistent} |`,
  )
  .join("\n")}

${rows.some((r) => r.failures.length) ? `### Failures\n\n${rows.flatMap((r) => r.failures.map((f) => `- ${r.advisor} — ${f}`)).join("\n")}\n` : ""}
### What the number means

The priority-sheet advisor does not consult the legal pool, which is not a
defect — it is the artefact this product replaces. A coach's priority sheet
knows which champions are strong and nothing about what the series has burned,
so **${headline.blocked} of ${headline.total}** of its suggestions
(${pct(headline.blocked, headline.total)}) would have been an illegal call. Every
one was caught by deterministic code before it reached the screen, and shown
with the game that burned it.

${
  key
    ? "The model-backed rows were measured against the live API."
    : "The model-backed advisor was **not measured** on this run: no `ANTHROPIC_API_KEY` was set. Re-run with one to fill those rows. Nothing in this file is estimated — a row that was not run is absent rather than guessed."
}

\`\`\`json
${JSON.stringify(metrics, null, 2)}
\`\`\`
`;

const out = join(import.meta.dirname, "..", "docs", "RESULTS.md");
writeFileSync(out, md);
console.log(
  `engine: ${groundTruth.length - engineFailures.length}/${groundTruth.length} exact; ` +
    `gate blocked ${headline.blocked}/${headline.total} from "${headline.advisor}" -> ${out}`,
);
if (engineFailures.length) process.exit(1);
